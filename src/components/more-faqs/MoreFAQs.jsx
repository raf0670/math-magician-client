function stripMarkdownLabel(text) {
    return text.replace(/^\*\*(.*)\*\*$/, "$1").trim();
}

function parseFaqs(rawText) {
    const items = [];
    let currentItem = null;

    rawText.split(/\r?\n/).forEach((line) => {
        if (line.startsWith("- ")) {
            if (currentItem) {
                items.push(currentItem);
            }

            currentItem = {
                question: stripMarkdownLabel(line.slice(2)),
                answer: []
            };
            return;
        }

        if (currentItem) {
            currentItem.answer.push(line.replace(/^ {4}/, ""));
        }
    });

    if (currentItem) {
        items.push(currentItem);
    }

    return items.map((item) => ({
        ...item,
        answer: item.answer.join("\n").trim()
    }));
}

function renderInline(text) {
    const parts = text.split(/(\*\*\*.+?\*\*\*|\*\*.+?\*\*|\*.+?\*)/g).filter(Boolean);

    return parts.map((part, index) => {
        if (part.startsWith("***") && part.endsWith("***")) {
            return (
                <strong key={index} className="italic">
                    {part.slice(3, -3)}
                </strong>
            );
        }

        if (part.startsWith("**") && part.endsWith("**")) {
            return <strong key={index}>{part.slice(2, -2)}</strong>;
        }

        if (part.startsWith("*") && part.endsWith("*")) {
            return <em key={index}>{part.slice(1, -1)}</em>;
        }

        return part;
    });
}

function MarkdownAnswer({ text }) {
    const blocks = [];
    let listItems = [];

    const flushList = () => {
        if (!listItems.length) {
            return;
        }

        blocks.push({
            type: "list",
            items: listItems
        });
        listItems = [];
    };

    text.split(/\r?\n/).forEach((line) => {
        const trimmed = line.trim();

        if (!trimmed) {
            flushList();
            return;
        }

        if (trimmed.startsWith("- ") || trimmed.startsWith("● ")) {
            listItems.push(trimmed.replace(/^(-|●)\s+/, ""));
            return;
        }

        flushList();
        blocks.push({
            type: "paragraph",
            text: trimmed
        });
    });

    flushList();

    return (
        <div className="space-y-3">
            {blocks.map((block, index) => {
                if (block.type === "list") {
                    return (
                        <ul key={index} className="list-disc space-y-1 pl-5">
                            {block.items.map((item, itemIndex) => (
                                <li key={itemIndex}>{renderInline(item)}</li>
                            ))}
                        </ul>
                    );
                }

                return (
                    <p key={index} className={block.text.startsWith("!") ? "text-base leading-none text-[#DFB15B]" : undefined}>
                        {renderInline(block.text)}
                    </p>
                );
            })}
        </div>
    );
}

